package dev.researchpath.benchmark;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.time.Clock;
import java.util.ArrayList;
import java.util.List;
import java.util.Locale;

import dev.researchpath.optimizer.OptimizerConfig;
import dev.researchpath.optimizer.Preferences;

/**
 * Offline benchmark command (playbook M08 gate): reads frozen dataset files and writes a Markdown report
 * and a JSON run record. No network, database or Spring context.
 *
 * <pre>usage: BenchmarkCli [--out DIR] DATASET.json...</pre>
 */
public final class BenchmarkCli {

	/** Baselines plus the optimizer with default preferences and the D12 default configuration. */
	static final List<Selector> SELECTORS = List.of(Baselines.RELEVANCE, Baselines.CITATION, Baselines.PROVIDER_ORDER,
			new OptimizerSelector(Preferences.DEFAULT, OptimizerConfig.DEFAULT));

	private BenchmarkCli() {
	}

	public static void main(String[] args) throws IOException {
		Path out = Path.of("target", "benchmarks");
		List<Path> datasets = new ArrayList<>();
		for (int i = 0; i < args.length; i++) {
			if (args[i].equals("--out") && i + 1 < args.length) {
				out = Path.of(args[++i]);
			} else {
				datasets.add(Path.of(args[i]));
			}
		}
		if (datasets.isEmpty()) {
			System.err.println("usage: BenchmarkCli [--out DIR] DATASET.json...");
			System.exit(2);
		}
		List<BenchmarkRunner.Run> runs = run(datasets, Clock.systemUTC());
		Files.createDirectories(out);
		Path json = out.resolve("baseline-runs.json");
		Path md = out.resolve("baseline-report.md");
		Files.writeString(json, DatasetIo.JSON.writeValueAsString(runs).replace("\r\n", "\n") + "\n",
				StandardCharsets.UTF_8);
		Files.writeString(md, markdown(runs), StandardCharsets.UTF_8);

		List<BenchmarkDataset> loaded = new ArrayList<>();
		List<SensitivitySweep.Row> sweep = new ArrayList<>();
		for (Path file : datasets) {
			BenchmarkDataset d = DatasetIo.read(file);
			loaded.add(d);
			sweep.addAll(SensitivitySweep.run(d, List.of(10, 20), OptimizerConfig.DEFAULT));
		}
		Files.writeString(out.resolve("optimizer-sweep.md"), SensitivitySweep.markdown(sweep), StandardCharsets.UTF_8);
		Files.writeString(out.resolve("optimizer-side-by-side.md"), SideBySide.markdown(loaded, 10), StandardCharsets.UTF_8);
		Files.writeString(out.resolve("reading-paths.md"), ReadingPaths.markdown(loaded), StandardCharsets.UTF_8);
		List<ExperienceSweep.Row> experience = new ArrayList<>();
		for (BenchmarkDataset d : loaded) {
			experience.addAll(ExperienceSweep.run(d, List.of(10, 20), OptimizerConfig.DEFAULT));
		}
		Files.writeString(out.resolve("experience-sweep.md"),
				ExperienceSweep.markdown(experience, OptimizerConfig.DEFAULT.experienceWeight()), StandardCharsets.UTF_8);
		System.out.println("Wrote " + md.toAbsolutePath() + ", " + json.toAbsolutePath()
				+ ", optimizer-sweep.md, optimizer-side-by-side.md, reading-paths.md and experience-sweep.md");
	}

	static List<BenchmarkRunner.Run> run(List<Path> datasets, Clock clock) throws IOException {
		List<BenchmarkRunner.Run> runs = new ArrayList<>();
		for (Path file : datasets) {
			runs.add(BenchmarkRunner.run(DatasetIo.read(file), file.getFileName().toString(), DatasetIo.sha256(file),
					SELECTORS, BenchmarkRunner.BUDGETS, clock));
		}
		return runs;
	}

	static String markdown(List<BenchmarkRunner.Run> runs) {
		StringBuilder sb = new StringBuilder("# Benchmark report: baselines and optimizer\n\n");
		sb.append("Generated by `BenchmarkCli` from frozen datasets (offline). Metrics are candidate-set proxies, ")
				.append("not learning outcomes; definitions and denominators are in `SelectionMetrics`.\n");
		for (BenchmarkRunner.Run r : runs) {
			sb.append("\n## ").append(r.topic()).append("\n\n")
					.append("- Dataset: `").append(r.datasetFile()).append("` (sha256 `").append(r.datasetSha256())
					.append("`), snapshot `").append(r.snapshotId()).append("`, ").append(r.candidateCount())
					.append(" candidates\n")
					.append("- Policies: normalizer v").append(r.snapshotPolicies().normalizerVersion())
					.append(", identity v").append(r.snapshotPolicies().identityPolicyVersion())
					.append(", relevance v").append(r.snapshotPolicies().relevancePolicyVersion())
					.append(" (snapshot); concept v").append(r.conceptPolicyVersion())
					.append(", text pipeline v").append(r.textPipelineVersion()).append(" (run)\n")
					.append("- Run: ").append(r.ranAt()).append(" on ").append(r.environment()).append("\n\n")
					.append("| Selector | k | Selected | Weighted coverage | Concepts | Relevance min / mean | ")
					.append("Redundancy (Jaccard) | Repeats | Citations known / median | Top-quartile share | ")
					.append("Years | Link / OA share | Select time |\n")
					.append("|---|---:|---:|---:|---:|---|---:|---:|---|---:|---|---|---:|\n");
			for (BenchmarkRunner.Result x : r.results()) {
				SelectionMetrics m = x.metrics();
				sb.append(String.format(Locale.ROOT,
						"| %s | %d | %d | %.3f | %d / %d | %.2f / %.2f | %.3f | %d | %.2f / %s | %.2f | %s–%s–%s | %.2f / %.2f | %d µs |%n",
						x.selector(), x.budget(), m.selectedCount(), m.weightedCoverage(), m.conceptsCovered(),
						m.conceptUniverseSize(), m.relevanceMin(), m.relevanceMean(), m.redundancyJaccard(),
						m.conceptRepeats(), m.citationsKnownShare(), m.citationsMedian() == null ? "–" : m.citationsMedian(),
						m.topQuartileCitationShare(), dash(m.yearMin()), dash(m.yearMedian()), dash(m.yearMax()),
						m.sourceLinkShare(), m.openAccessShare(), x.selectionNanos() / 1000));
			}
		}
		return sb.toString().replace("\r\n", "\n");
	}

	private static String dash(Integer v) {
		return v == null ? "–" : v.toString();
	}

}
