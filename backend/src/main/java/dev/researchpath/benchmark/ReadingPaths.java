package dev.researchpath.benchmark;

import java.util.ArrayList;
import java.util.HashMap;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.stream.Collectors;

import dev.researchpath.benchmark.BenchmarkDataset.Candidate;
import dev.researchpath.concept.ConceptModel;
import dev.researchpath.optimizer.GreedyOptimizer;
import dev.researchpath.optimizer.OptimizerConfig;
import dev.researchpath.optimizer.Preferences;
import dev.researchpath.optimizer.Preferences.Experience;
import dev.researchpath.optimizer.Preferences.Focus;
import dev.researchpath.sequence.PathPaper;
import dev.researchpath.sequence.ReadingPath;
import dev.researchpath.sequence.SequenceBuilder;

/**
 * Builds reading paths from frozen datasets (optimizer selection → sequence builder) and the M10 review artifact:
 * full paths for three topics, plus Beginner vs Advanced paths for decisions D09/D10.
 */
public final class ReadingPaths {

	private ReadingPaths() {
	}

	public static ReadingPath path(BenchmarkDataset d, int k, Preferences preferences) {
		ConceptModel model = SelectionMetrics.conceptModel(d);
		GreedyOptimizer.Result result = new OptimizerSelector(preferences, OptimizerConfig.DEFAULT).optimize(d, k);
		return SequenceBuilder.build(papers(d, model, result), preferences);
	}

	/** Selected candidates in selection order, with their included concepts and recorded decisions. */
	static List<PathPaper> papers(BenchmarkDataset d, ConceptModel model, GreedyOptimizer.Result result) {
		Map<String, String> labels = new HashMap<>();
		model.included().forEach(e -> labels.put(e.key(), e.label()));
		Map<String, Candidate> byId = d.candidates().stream().collect(Collectors.toMap(Candidate::openalexId, c -> c));
		List<PathPaper> out = new ArrayList<>();
		for (GreedyOptimizer.Decision dec : result.decisions()) {
			Candidate c = byId.get(dec.id());
			List<PathPaper.Concept> concepts = model.paperConcepts().getOrDefault((long) c.providerRank(), Map.of())
					.entrySet().stream()
					.filter(e -> labels.containsKey(e.getKey()))
					.map(e -> new PathPaper.Concept(e.getKey(), labels.get(e.getKey()), e.getValue()))
					.sorted(java.util.Comparator.comparing(PathPaper.Concept::key))
					.toList();
			out.add(new PathPaper(c.openalexId(), c.title(), c.publicationYear(), c.workType(), c.citedByCount(),
					c.citationPercentile(), c.sourceLink(), c.sourceLinkKind(), null, concepts, c.referencedWorkIds(), dec));
		}
		return out;
	}

	public static String markdown(List<BenchmarkDataset> datasets) {
		StringBuilder sb = new StringBuilder("# Reading paths — review artifact (M10, D09/D10)\n\n")
				.append("Generated by `BenchmarkCli` from the frozen datasets: optimizer selection (default configuration) ")
				.append("followed by `SequenceBuilder` v").append(SequenceBuilder.VERSION).append(". ")
				.append("\"Links\" are citation links among the selected papers only (→ cites, ← cited by); they ")
				.append("suggest background and are not prerequisites. Flags mark uncertain metadata.\n\n")
				.append("Always disclosed with a path:\n\n");
		SequenceBuilder.build(List.of(), Preferences.DEFAULT).disclosures().forEach(x -> sb.append("- ").append(x).append('\n'));
		for (BenchmarkDataset d : datasets) {
			sb.append("\n## ").append(d.topic()).append("\n");
			sb.append("\n### Stage structure by budget (Intermediate / Balanced)\n\n")
					.append("| k | Stages | Citation links | Cycles broken | Warnings |\n|---:|---|---:|---:|---|\n");
			for (int k : BenchmarkRunner.BUDGETS) {
				ReadingPath p = path(d, k, Preferences.DEFAULT);
				sb.append("| ").append(k).append(" | ")
						.append(p.stages().stream().map(s -> s.label() + " (" + (s.lastPosition() - s.firstPosition() + 1) + ")")
								.collect(Collectors.joining(" → ")))
						.append(" | ").append(p.citationLinks()).append(" | ").append(p.cycleBreaks()).append(" | ")
						.append(p.warnings().isEmpty() ? "–" : p.warnings().stream().map(w -> w.split(":")[0])
								.collect(Collectors.joining(", ")))
						.append(" |\n");
			}
			for (Preferences prefs : List.of(Preferences.DEFAULT, new Preferences(Experience.BEGINNER, Focus.BALANCED),
					new Preferences(Experience.ADVANCED, Focus.BALANCED))) {
				appendPath(sb, path(d, 10, prefs), "k = 10, " + name(prefs));
			}
			ReadingPath beginner = path(d, 10, new Preferences(Experience.BEGINNER, Focus.BALANCED));
			ReadingPath advanced = path(d, 10, new Preferences(Experience.ADVANCED, Focus.BALANCED));
			Set<String> shared = new LinkedHashSet<>(beginner.orderedIds());
			shared.retainAll(advanced.orderedIds());
			sb.append("\n**Beginner vs Advanced (k = 10):** ").append(shared.size()).append(" of 10 papers shared; ")
					.append("overview-marked papers ").append(overviews(beginner)).append(" vs ").append(overviews(advanced))
					.append(".\n");
		}
		return sb.toString().replace("\r\n", "\n");
	}

	private static long overviews(ReadingPath p) {
		return p.stages().stream().filter(s -> s.kind() == ReadingPath.StageKind.OVERVIEW)
				.mapToInt(s -> s.lastPosition() - s.firstPosition() + 1).sum();
	}

	private static void appendPath(StringBuilder sb, ReadingPath p, String heading) {
		sb.append("\n### ").append(heading).append("\n\n");
		sb.append("Citation links among selected papers: ").append(p.citationLinks());
		if (!p.warnings().isEmpty()) {
			sb.append("; warnings: ").append(String.join("; ", p.warnings()));
		}
		sb.append("\n");
		for (ReadingPath.Stage s : p.stages()) {
			sb.append("\n**Stage ").append(s.number()).append(" — ").append(s.label()).append(".** ").append(s.purpose())
					.append("\n\n| # | Paper | Year | Type | Why it's here | Links | Flags |\n|---:|---|---:|---|---|---|---|\n");
			for (ReadingPath.Item i : p.items().subList(s.firstPosition() - 1, s.lastPosition())) {
				String links = (i.cites().isEmpty() ? "" : "→ " + i.cites().stream().map(x -> "#" + x).collect(Collectors.joining(", ")))
						+ (i.cites().isEmpty() || i.citedBy().isEmpty() ? "" : "; ")
						+ (i.citedBy().isEmpty() ? "" : "← " + i.citedBy().stream().map(x -> "#" + x).collect(Collectors.joining(", ")));
				sb.append("| ").append(i.position()).append(" | ").append(escape(i.title())).append(" (").append(i.id())
						.append(") | ").append(i.year() == null ? "–" : i.year()).append(" | ")
						.append(i.workType() == null ? "–" : i.workType()).append(" | ")
						.append(i.reasons().stream().map(r -> escape(r.text())).collect(Collectors.joining(" ")))
						.append(" | ").append(links.isEmpty() ? "–" : links).append(" | ")
						.append(i.flags().isEmpty() ? "–" : i.flags().stream().map(Enum::name).collect(Collectors.joining(", ")))
						.append(" |\n");
			}
		}
	}

	private static String name(Preferences p) {
		return cap(p.experience().name()) + " / " + cap(p.focus().name());
	}

	private static String cap(String s) {
		return s.charAt(0) + s.substring(1).toLowerCase(java.util.Locale.ROOT);
	}

	private static String escape(String text) {
		return text.replace("<", "&lt;").replace("|", "\\|").replace("\n", " ");
	}

}
